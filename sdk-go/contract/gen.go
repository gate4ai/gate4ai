// Gen — Go-клиент действий из services манифеста поставщика m для пакета pkg:
// типы входа и выхода по схемам и методы поверх abi.Host.ServiceCall.
// Необязательные поля входа — с omitempty (нулевое значение не передаётся).
func Gen(m manifest.Manifest, pkg string) ([]byte, error) {
	if len(m.Services) == 0 {
		return nil, fmt.Errorf("connector %s has no services", m.Connector)
	}
	g := &gen{}
	g.p("// Code generated by `gate4ai contract gen` from the manifest of %s (contract %d). DO NOT EDIT.\n", m.Connector, m.Contract)
	g.p("\n// Package %s — клиент действий коннектора %s для service_call.\n", pkg, m.Connector)
	g.p("package %s\n\nimport \"github.com/gate4ai/gate4ai/sdk-go/abi\"\n\n", pkg)
	g.p("// Connector и Contract — поставщик и мажор контракта (как в capabilities.services потребителя).\n")
	g.p("const (\n\tConnector = %q\n\tContract  = %d\n)\n\n", m.Connector, m.Contract)
	g.p("// Client — вызовы действий %s через функции хоста.\ntype Client struct{ H *abi.Host }\n\n", m.Connector)
	g.p("// New — клиент поверх функций хоста коннектора.\nfunc New(h *abi.Host) Client { return Client{H: h} }\n\n")
	for _, name := range m.Services {
		a, _ := m.Find(name)
		typ := goName(name)
		in, out := typ+"Input", typ+"Output"
		g.doc(in, "аргументы "+m.Connector+"."+name)
		g.doc(out, "результат "+m.Connector+"."+name)
		g.object(in, &a.InputSchema, true)
		outType := "map[string]any"
		if a.OutputSchema != nil {
			if typeOf(a.OutputSchema) == manifest.TObject && len(a.OutputSchema.Properties) > 0 {
				g.object(out, a.OutputSchema, false)
				outType = out
			} else {
				outType = g.typ(out, a.OutputSchema, false)
			}
		}
		doc := strings.TrimSpace(a.Description)
		if doc == "" {
			doc = name
		}
		g.p("// %s — %s.%s: %s\n", typ, m.Connector, name, oneLine(doc))
		g.p("func (c Client) %s(in %s) (%s, abi.ExecResult, error) {\n", typ, in, outType)
		g.p("\tvar out %s\n\tres, err := c.H.ServiceCall(Connector, %q, in, &out)\n\treturn out, res, err\n}\n\n", outType, name)
	}
	src, err := format.Source(g.b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: %v\n%s", err, g.b.String())
	}
	return src, nil
}

type gen struct {
	b    bytes.Buffer
	done map[string]bool
	docs map[string]string // тип → чему он соответствует (комментарий)
}

func (g *gen) doc(name, what string) {
	if g.docs == nil {
		g.docs = map[string]string{}
	}
	if _, ok := g.docs[name]; !ok {
		g.docs[name] = what
	}
}

func (g *gen) p(f string, a ...any) { fmt.Fprintf(&g.b, f, a...) }

// object — именованная структура для схемы-объекта (вложенные объекты — свои типы).
func (g *gen) object(name string, s *manifest.Schema, input bool) {
	if g.done == nil {
		g.done = map[string]bool{}
	}
	if g.done[name] {
		return
	}
	g.done[name] = true
	g.p("// %s — %s.\n", name, g.docs[name])
	var body bytes.Buffer
	for _, p := range s.Properties {
		g.doc(name+goName(p.Name), "поле "+p.Name+" в "+name)
		g.doc(name+goName(p.Name)+"Item", "элемент "+p.Name+" в "+name)
		t := g.typ(name+goName(p.Name), p.Schema, input)
		tag := p.Name
		if input && !s.IsRequired(p.Name) {
			tag += ",omitempty"
		}
		if d := strings.TrimSpace(p.Schema.Description); d != "" {
			fmt.Fprintf(&body, "\t// %s\n", oneLine(d))
		}
		fmt.Fprintf(&body, "\t%s %s `json:%q`\n", goName(p.Name), t, tag)
	}
	g.p("type %s struct {\n%s}\n\n", name, body.String())
}

func (g *gen) typ(name string, s *manifest.Schema, input bool) string {
	switch typeOf(s) {
	case manifest.TString:
		return "string"
	case manifest.TInteger:
		return "int64"
	case manifest.TNumber:
		return "float64"
	case manifest.TBoolean:
		return "bool"
	case manifest.TArray:
		if s.Items == nil {
			return "[]any"
		}
		return "[]" + g.typ(name+"Item", s.Items, input)
	case manifest.TObject:
		if len(s.Properties) == 0 {
			return "map[string]any"
		}
		g.object(name, s, input)
		return name
	}
	return "any"
}

var initialisms = map[string]string{"id": "ID", "url": "URL", "uin": "UIN", "api": "API", "http": "HTTP", "json": "JSON",
	"ms": "MS", "uri": "URI", "html": "HTML", "png": "PNG", "css": "CSS", "ip": "IP", "otp": "OTP"}

// goName — snake_case → CamelCase с общепринятыми аббревиатурами.
func goName(s string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' }) {
		if v, ok := initialisms[strings.ToLower(part)]; ok {
			b.WriteString(v)
			continue
		}
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	if b.Len() == 0 {
		return "X"
	}
	return b.String()
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
